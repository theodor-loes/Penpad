"""Generates ../datefont.py: a small bitmap font for the date stamp (Norwegian letters included).
Run on a computer (needs Pillow):  python3 make_datefont.py
Change FONT / PX to restyle the date, then upload the new datefont.py to the Pico."""
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"
PX = 14          # font size in display pixels
SS = 4           # supersampling for smoother, bolder edges
THRESHOLD = 150  # lower = bolder
GAP = 1          # extra pixels between letters
DAYS = ("Man", "Tir", "Ons", "Tor", "Fre", "Lør", "Søn")
MONTHS = ("Jan", "Feb", "Mar", "Apr", "Mai", "Jun", "Jul", "Aug", "Sep", "Okt", "Nov", "Des")

chars = sorted(set("".join(DAYS) + "".join(MONTHS) + "0123456789 "))
big = ImageFont.truetype(FONT, PX * SS)
asc, desc = big.getmetrics()
cell_h = (asc + desc) // SS + 2

def render(ch):
    adv = max(1, round(big.getlength(ch) / SS))
    im = Image.new("L", ((adv + 4) * SS, cell_h * SS), 255)
    ImageDraw.Draw(im).text((2 * SS, SS), ch, font=big, fill=0)
    im = im.resize((adv + 4, cell_h), Image.BOX).point(lambda v: 0 if v < THRESHOLD else 255)
    return adv, im

glyphs = {c: render(c) for c in chars}
ink = [Image.eval(im, lambda v: 255 - v).getbbox() for _, im in glyphs.values()]
top = min(b[1] for b in ink if b); bottom = max(b[3] for b in ink if b)
GH = bottom - top
table = {}
for ch, (adv, im) in glyphs.items():
    rows = []
    for y in range(top, bottom):
        bits = 0
        for x in range(adv):                      # cell origin is x = 2
            bits = (bits << 1) | (1 if im.getpixel((x + 2, y)) == 0 else 0)
        rows.append(bits)
    # ink must not stick out of its cell, otherwise letters would clip
    bb = Image.eval(im, lambda v: 255 - v).getbbox()
    assert bb is None or (bb[0] >= 2 and bb[2] <= adv + 2), (ch, bb, adv)
    table[ch] = (adv, tuple(rows))

def width(s): return sum(table[c][0] for c in s) + GAP * (len(s) - 1)
maxw = max(width("%s %d %s" % (d, n, m)) for d in DAYS for n in range(1, 32) for m in MONTHS)
with open("../datefont.py", "w", encoding="utf-8") as f:
    f.write("# Generated by tools/make_datefont.py. Do not edit by hand.\n")
    f.write("GH = %d\nGAP = %d\nMAXW = %d\nGLYPHS = {\n" % (GH, GAP, maxw))
    for ch in chars:
        adv, rows = table[ch]
        f.write("    %r: (%d, %r),\n" % (ch, adv, rows))
    f.write("}\n")
print("glyph height", GH, "max text width", maxw, "glyphs", len(table))
