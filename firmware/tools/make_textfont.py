"""Generates ../textfont.py: two bitmap fonts (body and big) for the setup screen on the e-paper.
Run on a computer (needs Pillow):  python3 make_textfont.py
Includes Norwegian letters. Change SIZES / FONT to restyle, then upload the new textfont.py."""
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"
SIZES = {"BODY": 18, "BIG": 28}     # pixel heights of the two fonts
SS = 4                              # supersampling for smoother, bolder edges
THRESHOLD = 150                     # lower = bolder
GAP = 1                             # extra pixels between letters
CHARS = [chr(c) for c in range(32, 127)] + list("æøåÆØÅ")

def build(px):
    big = ImageFont.truetype(FONT, px * SS)
    asc, desc = big.getmetrics()
    cell_h = (asc + desc) // SS + 2
    glyphs = {}
    for ch in CHARS:
        adv = max(1, round(big.getlength(ch) / SS))
        im = Image.new("L", ((adv + 4) * SS, cell_h * SS), 255)
        ImageDraw.Draw(im).text((2 * SS, SS), ch, font=big, fill=0)
        im = im.resize((adv + 4, cell_h), Image.BOX).point(lambda v: 0 if v < THRESHOLD else 255)
        glyphs[ch] = (adv, im)
    ink = [Image.eval(im, lambda v: 255 - v).getbbox() for _, im in glyphs.values()]
    top = min(b[1] for b in ink if b); bottom = max(b[3] for b in ink if b)
    table = {}
    for ch, (adv, im) in glyphs.items():
        bb = Image.eval(im, lambda v: 255 - v).getbbox()
        x0, x1 = 2, adv + 2                       # the letter's own cell
        if bb is not None:                        # ink that leans outside the cell (like j) widens it, so nothing clips
            x0, x1 = min(x0, bb[0]), max(x1, bb[2])
        rows = []
        for y in range(top, bottom):
            bits = 0
            for x in range(x0, x1):
                bits = (bits << 1) | (1 if im.getpixel((x, y)) == 0 else 0)
            rows.append(bits)
        table[ch] = (x1 - x0, tuple(rows))
    return bottom - top, table

with open("../textfont.py", "w", encoding="utf-8") as f:
    f.write("# Generated by tools/make_textfont.py. Do not edit by hand.\n")
    f.write("# NAME = (glyph height, gap between letters, {char: (width, rows)}); each row is a bit pattern, leftmost pixel = top bit.\n")
    for name, px in SIZES.items():
        gh, table = build(px)
        f.write("%s = (%d, %d, {\n" % (name, gh, GAP))
        for ch in CHARS:
            adv, rows = table[ch]
            f.write("    %r: (%d, %r),\n" % (ch, adv, rows))
        f.write("})\n")
        print(name, "height", gh, "glyphs", len(table))
